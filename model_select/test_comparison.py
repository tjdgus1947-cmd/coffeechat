# ------------------------------------------------------------------
# 임베딩 매칭 실행
# ------------------------------------------------------------------
print("\n⏳ 다국어 AI 모델 로딩 중... ")
# 한국어 문맥 파악을 위해 성능 좋은 다국어 모델 사용
model = SentenceTransformer('sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2')

# 임베딩 생성
query_embedding = model.encode(mentee_intro, convert_to_tensor=True)
doc_embeddings = model.encode(mentors, convert_to_tensor=True)

# 코사인 유사도 계산
cosine_scores = util.cos_sim(query_embedding, doc_embeddings)[0]

# 결과 리스트 생성
results = []
for i in range(len(mentors)):
    score = cosine_scores[i].item() * 100
    # 멘토 소개의 첫 줄만 가져와서 제목으로 사용
    title = mentors[i].strip().split('\n')[0] 
    results.append((title, score))

# 점수순 정렬
results.sort(key=lambda x: x[1], reverse=True)


# ------------------------------------------------------------------
# 결과 출력
# ------------------------------------------------------------------

print("="*80 + "\n")

for title, score in results:
    if score >= 65:
        grade = "🥇 (찰떡 매칭)"
    elif score >= 45:
        grade = "🥈 (어느 정도 관련)"
    elif score >= 30:
        grade = "🥉 (분야 다름)"
    else:
        grade = "❌ (관련 없음)"
        
    print(f"멘토: {title[:35]:<35}... | 유사도: {score:.1f}점 ")

print("\n" + "-" * 80)